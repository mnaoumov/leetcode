namespace LeetCode.Templates;

public static class UnionFindTemplate
{
    public sealed class UnionFind<T> where T : IEquatable<T>
    {
        private readonly Dictionary<T, T> _roots = new();
        private readonly Dictionary<T, int> _ranks = new();

        /// <summary>The number of disjoint sets among the elements seen so far.</summary>
        public int Count { get; private set; }

        public T Find(T x)
        {
            if (_roots.TryAdd(x, x))
            {
                Count++;
                return x;
            }

            var root = _roots[x];
            return root.Equals(x) ? x : _roots[x] = Find(root);
        }

        public void Union(T x, T y)
        {
            var rootX = Find(x);
            var rootY = Find(y);

            if (rootX.Equals(rootY))
            {
                return;
            }

            Count--;
            var rankX = GetRank(rootX);
            var rankY = GetRank(rootY);

            if (rankX < rankY)
            {
                _roots[rootX] = rootY;
            }
            else if (rankX > rankY)
            {
                _roots[rootY] = rootX;
            }
            else
            {
                _roots[rootX] = rootY;
                _ranks[rootY] = rankY + 1;
            }
        }

        private int GetRank(T x) => _ranks.GetValueOrDefault(x, 1);

        public bool Connected(T x, T y) => Find(x).Equals(Find(y));
    }
}

using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace LeetCode.Problems.Generators;

/// <summary>
/// Records the folder of every problem: for each <c>LeetCode.Problems.*</c> namespace, the folder of the source file
/// that declares it, relative to the project, as <c>[assembly: ProblemDirectory(namespace, folder)]</c>.
/// The test framework reads the attributes, so it never has to rebuild a folder name from a namespace.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ProblemDirectoryGenerator : IIncrementalGenerator
{
    private const string NamespacePrefix = "LeetCode.Problems.";

    private static readonly DiagnosticDescriptor NamespaceInTwoFolders = new(
        "LC0001",
        "A problem namespace is declared in two folders",
        "Namespace '{0}' is declared in both '{1}' and '{2}': each problem folder needs a namespace of its own",
        "LeetCode",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declarations = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is BaseNamespaceDeclarationSyntax,
                static (syntaxContext, _) => ToDeclaration((BaseNamespaceDeclarationSyntax) syntaxContext.Node))
            .Where(static declaration => declaration.Namespace.StartsWith(NamespacePrefix, StringComparison.Ordinal))
            .Collect();

        var projectDirectory = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.MSBuildProjectDirectory", out var directory)
                ? directory
                : "");

        context.RegisterSourceOutput(declarations.Combine(projectDirectory),
            static (sourceContext, input) => Emit(sourceContext, input.Left, input.Right));
    }

    private static Declaration ToDeclaration(BaseNamespaceDeclarationSyntax syntax) =>
        new(syntax.Name.ToString(), Path.GetDirectoryName(syntax.SyntaxTree.FilePath) ?? "", syntax.Name.GetLocation());

    private static void Emit(SourceProductionContext context, ImmutableArray<Declaration> declarations,
        string projectDirectory)
    {
        var directories = new SortedDictionary<string, string>(StringComparer.Ordinal);

        foreach (var declaration in declarations)
        {
            var directory = ToRelativePath(projectDirectory, declaration.Directory);

            if (!directories.TryGetValue(declaration.Namespace, out var knownDirectory))
            {
                directories.Add(declaration.Namespace, directory);
            }
            else if (knownDirectory != directory)
            {
                var (first, second) = string.CompareOrdinal(knownDirectory, directory) < 0
                    ? (knownDirectory, directory)
                    : (directory, knownDirectory);
                context.ReportDiagnostic(Diagnostic.Create(NamespaceInTwoFolders, declaration.Location,
                    declaration.Namespace, first, second));
            }
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");

        foreach (var pair in directories)
        {
            source.Append("[assembly: global::LeetCode.Base.ProblemDirectory(")
                .Append(ToLiteral(pair.Key))
                .Append(", ")
                .Append(ToLiteral(pair.Value))
                .AppendLine(")]");
        }

        context.AddSource("ProblemDirectories.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    // The path is stored with '/' so the attribute reads the same whichever OS compiled it.
    internal static string ToRelativePath(string projectDirectory, string directory)
    {
        var project = projectDirectory.Replace('\\', '/').TrimEnd('/') + "/";
        var path = directory.Replace('\\', '/');

        return path.StartsWith(project, StringComparison.OrdinalIgnoreCase) ? path.Substring(project.Length) : path;
    }

    private static string ToLiteral(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private sealed record Declaration(string Namespace, string Directory, Location Location)
    {
        // The location only reports a clash; leaving it out lets an unchanged declaration skip the output step.
        public bool Equals(Declaration? other) =>
            other is not null && Namespace == other.Namespace && Directory == other.Directory;

        public override int GetHashCode() => (Namespace, Directory).GetHashCode();
    }
}
